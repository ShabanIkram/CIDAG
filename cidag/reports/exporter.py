import csv
import io 
import json 
from datetime import datetime, timezone


def to_json(result: dict) -> str:
    return json.dumps(result, indent=2, default=str)


_SARIF_LEVELS = {
    "CRITICAL": "error", "HIGH": "error",
    "MEDIUM": "warning", "LOW": "note", "INFO": "note",
}


def to_sarif(findings: list, repo_uri: str = "https://github.com/ShabanIkram/CIDAG") -> str:
    """SARIF 2.1.0 for GitHub code scanning / CI security gates."""
    rules: dict[str, dict] = {}
    results: list[dict] = []
    for f in findings:
        severity = f.severity.name if hasattr(f.severity, "name") else str(f.severity)
        rule_id = str(f.check_id)
        if rule_id not in rules:
            rules[rule_id] = {
                "id": rule_id,
                "name": rule_id.replace("-", ""),
                "shortDescription": {"text": str(f.title)},
                "help": {"text": str(f.remediation or f.title)},
                "properties": {"tags": [f.module] + ([f.cve] if f.cve else [])},
            }
        results.append({
            "ruleId": rule_id,
            "level": _SARIF_LEVELS.get(severity, "note"),
            "message": {"text": str(f.title)},
            "locations": [{"physicalLocation": {
                "artifactLocation": {"uri": str(f.target)}}}],
            "partialFingerprints": {"cidagFindingId": str(f.id)},
            "properties": {
                "module": f.module,
                "severity": severity,
                **({"cve": f.cve} if f.cve else {}),
                **({"account": f.account} if f.account else {}),
                **({"identityArn": f.identity_arn} if f.identity_arn else {}),
                **({"compliance": f.compliance} if f.compliance else {}),
                **({"remediation": f.remediation} if f.remediation else {}),
            },
        })
    doc = {
        "$schema": "https://json.schemastore.org/sarif-2.1.0.json",
        "version": "2.1.0",
        "runs": [{
            "tool": {"driver": {
                "name": "CIDAG",
                "version": "2.0",
                "informationUri": repo_uri,
                "rules": list(rules.values()),
            }},
            "results": results,
        }],
    }
    return json.dumps(doc, indent=2, default=str)


def to_csv(findings: list[dict]) -> str:
    fields = ["severity", "type", "identity", "reason", "remediation"]
    buf = io.StringIO()
    writer = csv.DictWriter(buf, fieldnames=fields, extrasaction="ignore")
    writer.writeheader()
    for f in findings:
        writer.writerow(f)
    return buf.getvalue()


def to_markdown(inventory: dict, result: dict) -> str:
    now = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    s = result["summary"]
    lines = [
     "# CIDAG - Cloud Identity Attack Graph Report",
        "",
        f"- **Generated:** {now}",
        f"- **Account:** {inventory.get('account_id', 'unknown')}",
        f"- **Nodes/Edges:** {s['nodes']} / {s['edges']}",
        f"- **Admin principals:** {s['admins']}",
        f"- **Findings:** {s['findings']}",
        "",
        "## Findings",
        "",   
    ]
    if not result["findings"]:
        lines.append("_No findings._")
    for i, f in enumerate(result["findings"], 1):
        lines += [
            f"### {i}. [{f['severity']}] {f['type']} - {f.get('identity', '')}",
            "",
            f"- **Reason:** {f.get('reason', '')}",
        ]
        if f.get("chain"):
            lines.append(f"- **Attack chain:** `{'->'.join(f['chain'])}`")
        if f.get("remediation"):
            lines.append(f"- **Remediation:** {f['remediation']}")
        lines.append("")
    lines += [
        "## Methodology",
        "",
        "1. Collected IAM identities, policies, trust relationships",
        "2. Computed effective permissions (Deny precedence, wildcards)",
        "3. Detected escalation rules (Rhino-style chains) and graph attack paths",
        "",
        "_Generated by CIDAG (https://github.com/ShabanIkram/cidag)_",
    ]
    return "\n".join(lines)
